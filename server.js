const OFFICIAL_HOSTS = ["tnpsc.gov.in","www.tnpsc.gov.in","ssc.gov.in","www.ssc.gov.in","upsc.gov.in","www.upsc.gov.in","ibps.in","www.ibps.in","indianrailways.gov.in","www.indianrailways.gov.in"];
function officialUrl(s) { try { const u = new URL(String(s)); return u.protocol === "https:" && OFFICIAL_HOSTS.includes(u.hostname) ? u : null; } catch (e) { return null; } }

app.get("/api/getfile", async (req, res) => {
  const u = officialUrl(req.query.url);
  if (!u) return res.status(400).send("Only official government sites are allowed");
  try {
    const r = await fetch(u, { redirect: "follow" });
    if (!r.ok) return res.status(502).send("The site refused the download");
    if (!officialUrl(r.url)) return res.status(400).send("Redirect blocked");
    if (!/pdf|octet-stream/.test(r.headers.get("content-type") || "")) return res.status(415).send("That link is not a PDF");
    const buf = Buffer.from(await r.arrayBuffer());
    if (buf.length > 25e6) return res.status(413).send("File too large");
    res.type("application/pdf").send(buf);
  } catch (e) { res.status(502).send("Download failed"); }
});

app.get("/api/pdflinks", async (req, res) => {
  const u = officialUrl(req.query.url);
  if (!u) return res.status(400).send("Only official government sites are allowed");
  try {
    const r = await fetch(u, { redirect: "follow" });
    if (!r.ok || !officialUrl(r.url)) return res.status(502).send("Could not open the page");
    const html = await r.text(), out = [], seen = new Set();
    const re = /<a\s[^>]*href=["']([^"']+\.pdf[^"']*)["'][^>]*>([\s\S]*?)<\/a>/gi;
    let m;
    while ((m = re.exec(html)) && out.length < 300) {
      let link; try { link = new URL(m[1], r.url); } catch (e) { continue; }
      if (!officialUrl(link.href) || seen.has(link.href)) continue;
      seen.add(link.href);
      const label = m[2].replace(/<[^>]*>/g, " ").replace(/\s+/g, " ").trim() || decodeURIComponent(link.pathname.split("/").pop());
      out.push({ url: link.href, label: label.slice(0, 120) });
    }
    res.json(out);
  } catch (e) { res.status(502).send("Could not read the page"); }
});

